export function applyCourseContentOverrides(levels) {
  return levels.map((level) => ({
    ...level,
    questions: level.questions.map((question, index) => {
      const overrideKey = `L${String(level.level).padStart(3, "0")}-Q${String(index + 1).padStart(3, "0")}`;
      const override = COURSE_CONTENT_OVERRIDES.get(question.id) ?? COURSE_CONTENT_OVERRIDES.get(overrideKey) ?? {};
      let sentence = override.sentence ?? applySentenceQualityFixes(question.sentence);
      const wrongSentence = override.wrongSentence ?? applySentenceQualityFixes(question.wrongSentence);

      if (/ is reading a book\.$/.test(sentence) && / is holding a picture card\.$/.test(wrongSentence)) {
        sentence = sentence.replace(/ is reading a book\.$/, " is holding an open book.");
      }
      if (/ is opening a box\.$/.test(sentence) && / is holding an open book\.$/.test(wrongSentence)) {
        sentence = sentence.replace(/ is opening a box\.$/, " is holding an open box.");
      }
      if (/ is flying a kite\.$/.test(sentence) && / is holding a paper plane\.$/.test(wrongSentence)) {
        sentence = sentence.replace(/ is flying a kite\.$/, " is holding a kite.");
      }

      return {
        ...question,
        ...override,
        sentence,
        wrongSentence,
        ...(question.correctImagePrompt
          ? { correctImagePrompt: syncImagePrompt(question.correctImagePrompt, sentence) }
          : {}),
        ...(question.wrongImagePrompt
          ? { wrongImagePrompt: syncImagePrompt(question.wrongImagePrompt, wrongSentence) }
          : {})
      };
    })
  }));
}

function syncImagePrompt(prompt, sentence) {
  const marker = ". Scene:";
  const markerIndex = prompt.indexOf(marker);
  return markerIndex >= 0 ? `${prompt.slice(0, markerIndex)}${marker} ${sentence}` : prompt;
}

export function applySentenceQualityFixes(sentence) {
  return sentence
    .replace(/ is reading a card\.$/, " is holding a picture card.")
    .replace(/ is opening a book\.$/, " is holding an open book.")
    .replace(/ is closing a book\.$/, " is holding a closed book.")
    .replace(/ is closing a box\.$/, " is holding a closed box.")
    .replace(/ is folding a towel\.$/, " is holding a folded towel.")
    .replace(/ is folding a shirt\.$/, " is holding a folded shirt.");
}
