import { writeFile } from "node:fs/promises";

import { textbookLevels as stageOneLevels } from "../src/course/textbook-levels-001-050.generated.mjs";
import { stageTwoTextbookLevels } from "../src/course/textbook-levels-051-100.generated.mjs";
import { textbookLevels as laterLevels } from "../src/course/textbook-levels-101-300.generated.mjs";
import { applyCourseContentOverrides } from "./lib/course-content-overrides.mjs";

const correctedStageOne = applyCourseContentOverrides(stageOneLevels);
const correctedStageTwo = applyCourseContentOverrides(stageTwoTextbookLevels);
const correctedLater = applyCourseContentOverrides(laterLevels);
const correctedFirstHundred = [...correctedStageOne, ...correctedStageTwo];
const correctedAll = [...correctedFirstHundred, ...correctedLater];

await writeGenerated(
  "src/course/textbook-levels-001-050.generated.mjs",
  "textbookLevels",
  correctedStageOne,
  "scripts/apply-course-content-overrides.mjs"
);
await writeGenerated(
  "src/course/textbook-levels-051-100.generated.mjs",
  "stageTwoTextbookLevels",
  correctedStageTwo,
  "scripts/apply-course-content-overrides.mjs"
);
await writeGenerated(
  "src/course/textbook-levels-001-100.generated.mjs",
  "textbookLevels",
  correctedFirstHundred,
  "scripts/apply-course-content-overrides.mjs"
);
await writeGenerated(
  "src/course/textbook-levels-101-300.generated.mjs",
  "textbookLevels",
  correctedLater,
  "scripts/apply-course-content-overrides.mjs"
);
await writeGenerated(
  "src/course/textbook-levels-001-300.generated.mjs",
  "textbookLevels",
  correctedAll,
  "scripts/apply-course-content-overrides.mjs"
);

console.log(`Applied ${correctedFirstHundred.length} corrected levels to generated course data.`);

async function writeGenerated(path, exportName, value, generator) {
  await writeFile(
    path,
    `// Generated by ${generator}.\n// Do not edit by hand.\n\nexport const ${exportName} = ${JSON.stringify(value, null, 2)};\n`,
    "utf8"
  );
}
